#
# 책임:
#   - Judge 결과 통합
#   - 전문 영역별 품질 점수 계산
#   - confidence 별도 감시
#   - Judge 간 불일치 감지
#   - critical risk 처리
#   - Judge reliability 반영
#   - PASS / REWRITE / REVIEW 결정
#
#
# V3.2 핵심 변경:
#
# 1. confidence가 품질 점수를 직접 깎지 않는다.
#
#    이전:
#       score 8
#       confidence 0.7
#       → adjusted_score 5.6
#
#    문제:
#       "콘텐츠 품질"과
#       "Judge가 자신의 판단을 확신하는 정도"를
#       같은 값처럼 처리하게 됨.
#
#
#    현재:
#       score 8
#       confidence 0.7
#
#       품질 점수 = 8
#       confidence = 0.7
#
#       confidence 문제는 별도로 탐지한다.
#
#
# 2. Domain Floor 추가
#
#    전체 평균이 높아도
#    특정 전문 영역이 너무 약하면 PASS 금지.
#
#    예:
#
#       Hook     8
#       Novelty  6
#       Fact     8
#       Visual   8
#
#       평균만 보면 PASS 가능하지만
#       Novelty가 최소 품질 기준 미달.
#
#       → REWRITE
#
#
# 3. 역할 분리
#
#    score
#       = 콘텐츠 품질
#
#    confidence
#       = Judge가 판정에 얼마나 확신하는가
#
#    reliability
#       = 장기 데이터상 Judge를 얼마나 신뢰하는가
#
#    disagreement
#       = 같은 전문 영역의 Judge들이 얼마나 충돌하는가
#
# ============================================================


